from datetime import datetime, timezone
from enum import Enum
from typing import Annotated, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, field_validator


class Category(str, Enum):
    network = "Network / Wi-Fi"
    software = "Software"
    hardware = "Hardware"
    account = "Account / Login"
    email = "Email"
    other = "Other"


class Priority(str, Enum):
    low = "Low"
    medium = "Medium"
    high = "High"


class Status(str, Enum):
    open = "Open"
    in_progress = "In Progress"
    resolved = "Resolved"


Title = Annotated[str, StringConstraints(strip_whitespace=True, min_length=3, max_length=160)]
Description = Annotated[
    str, StringConstraints(strip_whitespace=True, min_length=10, max_length=6000)
]
Note = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=1000)]


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class DiagnoseRequest(StrictModel):
    title: Title
    description: Description
    category: Category | None = None


class Analysis(StrictModel):
    category: Category
    priority: Priority
    possible_causes: list[Note] = Field(min_length=1, max_length=6)
    solution_steps: list[Note] = Field(min_length=1, max_length=8)
    needs_human_support: bool
    escalation_reason: Note
    uncertainty: Note
    article_ids: list[str] = Field(max_length=3)


class Article(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    title: str
    category: Category
    symptoms: str
    solution_steps: list[str]


class Diagnosis(StrictModel):
    mode: Literal["Rule-based Demo Mode", "AI-Powered Analysis"]
    analysis: Analysis
    recommended_articles: list[Article]
    notice: str | None = None
    clarifying_questions: list[str] = Field(default_factory=list, max_length=3)


class TicketCreate(DiagnoseRequest):
    # A preview is never trusted from the browser: diagnosis is generated by the server.
    diagnosis_id: UUID | None = None


class DiagnosisPreview(Diagnosis):
    diagnosis_id: UUID


class TicketUpdate(StrictModel):
    status: Status


class TicketRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    title: str
    description: str
    category: Category
    priority: Priority
    status: Status
    created_at: datetime
    updated_at: datetime
    diagnosis: Diagnosis

    @field_validator("created_at", "updated_at")
    @classmethod
    def sqlite_utc(cls, value):
        # SQLite drops tzinfo; all timestamps are stored as UTC.
        return value.replace(tzinfo=timezone.utc) if value.tzinfo is None else value


class Stats(BaseModel):
    total_tickets: int
    by_status: dict[str, int]
    by_category: dict[str, int]
    by_priority: dict[str, int]
    sla_breaches: int = 0
    sla_due_soon: int = 0
    resolved_sla_breaches: int = 0
    average_resolution_hours: float | None = None
    measured_resolutions: int = 0
    estimated_resolutions: int = 0


class EventRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: int
    ticket_id: str
    event_type: str
    previous_value: str | None
    new_value: str | None
    timestamp: datetime
    note: str | None

    _utc = field_validator("timestamp")(TicketRead.sqlite_utc.__func__)


class SupportNote(StrictModel):
    note: Note


class FeedbackCreate(StrictModel):
    outcome: Literal["solved", "still_having_issues"]
    note: Note | None = None
    ticket_id: UUID | None = None


class FeedbackRead(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    diagnosis_id: str
    outcome: str
    note: str | None
    ticket_id: str | None
    followup_diagnosis_id: str | None
    created_at: datetime

    _utc = field_validator("created_at")(TicketRead.sqlite_utc.__func__)


class FollowupRequest(StrictModel):
    details: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=10, max_length=2000)
    ]
    ticket_id: UUID | None = None


class ApplyDiagnosis(StrictModel):
    diagnosis_id: UUID


class DuplicateMatch(BaseModel):
    ticket_id: str
    title: str
    status: Status
    similarity: float
    shared_terms: list[str]


class SLARead(BaseModel):
    ticket_id: str
    due_at: datetime
    resolved_at: datetime | None
    resolution_estimated: bool
    state: Literal["On Track", "Due Soon", "Breached", "Resolved"]
    breached: bool
    remaining_seconds: float
    elapsed_hours: float
    as_of: datetime


class SLATicket(SLARead):
    title: str
    priority: Priority
    status: Status
